stocks_data = []

# ======================================================
# MOEX API
# ======================================================
with MoexClient() as client:
    logger.info("MOEX CLIENT CREATED")

    stock_service = StockForeignService(client)
    candle_service = StockForeignCandleService(client, stock_service)
    sector_service = SectorStockForeignService()

    for secid in SECIDS:
        logger.info("LOAD FOREIGN STOCK M10 SECID=%s", secid)
        limiter.wait()

        try:
            # 1. Получаем базовую информацию об акции
            stock = stock_service.get_by_secid(secid)
            if not stock:
                logger.warning("STOCK NOT FOUND SECID=%s", secid)
                continue

            # 2. Получаем страну и сектор через сервис
            country = sector_service.get_country(secid)
            sector = sector_service.get_sector(secid)

            isin = getattr(stock, 'isin', 'N/A')

            logger.info(
                """
STOCK INFO
SECID=%s
ISIN=%s
COUNTRY=%s
SECTOR=%s
BOARD=%s
""",
                stock.secid,
                isin,
                country,
                sector,
                stock.board,
            )

            # 3. Загружаем свечи (interval=10 для 10-минутных)
            candles = candle_service.get(
                secid=secid,
                date_from=DATE_FROM,
                date_till=DATE_TO,
                interval=INTERVAL,
            )

            logger.info("M10 CANDLES RECEIVED SECID=%s COUNT=%s", secid, len(candles))

            # 4. Сохраняем в память для последующей записи в БД
            stocks_data.append((stock, candles, country, sector))

        except Exception as error:
            logger.exception("STOCK LOAD ERROR SECID=%s ERROR=%s", secid, error)

